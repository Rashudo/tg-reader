/**
 * Ключевые слова. Регистр не учитывается, «ё» = «е».
 *
 * 'слово'        — ищется как подстрока: 'телевизор' поймает «телевизоры»,
 *                  «телевизором», «телевизор-приставка»
 * { word: 'тв' } — ищется только как отдельное слово: поймает «ТВ-приставка»
 *                  и «смарт тв», но не «ответ», «твой», «творог»
 *
 * Короткие ключи (2-3 буквы) почти всегда стоит писать через { word: ... },
 * иначе они цепляют половину словаря.
 *
 * Правьте файл и перезапускайте бота (npm start).
 */
module.exports = [
  { word: 'тв' },   // кириллицей — «ТВ-приставка», «Смарт ТВ»
  'tv',             // латиницей — «Smart TV», «TV-box», «TVs»
  'телевизор',
  'box',
  { word: 'lg' },
  'tesla',
];
