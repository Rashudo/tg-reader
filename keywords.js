/**
 * Ключевые слова. Регистр не учитывается, «ё» = «е».
 *
 * 'слово'        — ищется как подстрока: 'телевизор' поймает «телевизоры»,
 *                  «телевизором», «телевизор-приставка»
 * { word: 'тв' } — ищется только как отдельное слово: поймает «ТВ-приставка»
 *                  и «смарт тв», но не «ответ», «твой», «творог»
 *
 * Короткие ключи (2-3 буквы) почти всегда стоит писать через { word: ... },
 * иначе они цепляют половину словаря. Проверено на 2000 постов канала:
 * подстрока 'тв' давала только «Твердая обложка», 'box' — «XBox» и «Timebox-evo»,
 * 'tv' — сербское «ubistvo».
 *
 * Правьте файл и перезапускайте бота (npm start).
 */
module.exports = [
  { word: 'тв' },      // «Держатель ТВ», «Смарт ТВ», «ТВ-приставка»
  { word: 'tv' },      // «Smart TV», «Mi TV Stick»
  'телевизор',         // все падежи разом
  'televizor',         // сербское написание — канал в Нови-Саде
  { word: 'box' },     // «TV box», но не «XBox» и не «Timebox»
  { word: 'lg' },
  'tesla',
];
